#!/usr/bin/env bash
# Generate env.<round>-<nodekey>.yihou.sh for the dcp_pd harness.
# Usage: mk_env.yihou.sh NODEKEY ROUND VARIANT     (VARIANT: A0 | A | B | Be | Bperf | Beperf)
#   A0     non-DCP PD baseline, image sglang (no overlay), sim acc 3.61
#   A      non-DCP PD baseline (e2g shape: both legs TP4 DPA), overlay, sim acc 3.61
#   B      DCP4 decode, prefill TP4 no-DPA (design s7 main E2E arm), overlay, REAL draft (T4a-d)
#   Be     DCP4 decode, prefill TP4+DPA4 (T4e), overlay, REAL draft
#   Bperf/Beperf  as B/Be with SGLANG_SIMULATE_ACC_LEN=3.61 (AgentX scoring, same as the 22k baseline)
# At source time: PD_EXTRA (extra KEY=VALUE overrides, e.g. DECODE_EXTRA_ARGS_ADD=--disable-cuda-graph), PD_JOB (spur job holding the node) is required; PD_OVERLAY (.../python/sglang) overrides
# the overlay (default: branch dev/yihou/glm52_dcp_pd @ae529c96bf synced to src/, recipe already committed).
# DCP variants: decode mem-fraction 0.85 (t4_runbook / mixrun DCP4), prefill unchanged from e2g.
set -euo pipefail
H=/shared_nfs/yihou_glm52/dcp_pd_20261021/pd/harness
nk=$1; round=$2; v=$3
topo=$H/topology.yihou.$nk.tsv
ip=$(awk -F'\t' '$1=="decode"{print $3}' "$topo"); node=$(awk -F'\t' '$1=="decode"{print $2}' "$topo")
[[ -n "$ip" && -n "$node" ]] || { echo "bad topology $topo" >&2; exit 2; }
ov='SGLANG_OVERLAY=${PD_OVERLAY:-/shared_nfs/yihou_glm52/dcp_pd_20261021/src/sglang-ae529c96bf/python/sglang}'
case "$v" in
  A0)     ovr="DCP_DECODE=1 PREFILL_ARM=dpa"; ov="" ;;
  A)      ovr="DCP_DECODE=1 PREFILL_ARM=dpa" ;;
  B)      ovr="DECODE_MEM_FRACTION=0.85 DCP_DECODE=4 PREFILL_ARM=tp DECODE_SIMULATE_ACC_LEN=" ;;
  Be)     ovr="DECODE_MEM_FRACTION=0.85 DCP_DECODE=4 PREFILL_ARM=dpa DECODE_SIMULATE_ACC_LEN=" ;;
  Bperf)  ovr="DECODE_MEM_FRACTION=0.85 DCP_DECODE=4 PREFILL_ARM=tp" ;;
  Beperf) ovr="DECODE_MEM_FRACTION=0.85 DCP_DECODE=4 PREFILL_ARM=dpa" ;;
  *) echo "unknown variant $v" >&2; exit 2 ;;
esac
out=$H/env.$round-$nk.yihou.sh
cat > "$out" <<EOT
# dcp_pd_20261021 (pdrun) round $round on $node, variant $v (generated by tools/mk_env.yihou.sh $*)
export H=$H
export YIHOU_NODE=$node YIHOU_IP=$ip YIHOU_JOB=\${PD_JOB:?set PD_JOB (spur job holding $node)} YIHOU_ROUND=$round
unset EXPECTED_IMAGE_ID
export CONFIG=\$H/config.yihou.dcp.sh
export YIHOU_OVERRIDES="$ovr ${ov} CONC=\${PD_CONC:-4} ENGINE_PID_HOST=0 IPC_MODE_LEGACY=0 DEBUG_AGENT=1 DECODE_PID_OFFSET=30000 \${PD_EXTRA:-}"
EOT
echo "$out"
